import { CREDIT_COSTS } from '@parlante/shared';
import type { Avatar, Gender } from '@parlante/shared';
import { Dices, Sparkles, Timer, UserRoundX } from 'lucide-react';
import { useEffect, useRef, useState } from 'react';
import type { FormEvent } from 'react';
import { useTranslation } from 'react-i18next';
import { apiClient, isApiError, toApiError } from '@/lib/api';
import type { ApiError } from '@/lib/api';
import { useFormat } from '@/lib/format';
import { useSession } from '@/lib/session';
import { Button, Input, SegmentedControl, Textarea } from '@/ui';
import { Callout, CostLine, FailureNote, portraitSeconds } from '@/features/avatars/kit';
import type { EngineStatus } from '@/features/avatars/kit';
import {
  GENDERS,
  NAME_MAX,
  PROMPT_MAX,
  SEED_MAX,
  nameProblem,
  parseSeed,
  promptProblem,
} from '../lib/form';
import type { Allowance } from '../lib/form';

const EXAMPLES = ['presenter', 'teacher', 'creator', 'senior'] as const;

export interface GenerateFormProps {
  engine: EngineStatus | null;
  /** The engine can generate AND prepare a portrait right now. */
  canGenerate: boolean;
  allowance: Allowance | null;
  onCreated: (avatar: Avatar) => void;
}

/**
 * Description → portrait of a synthetic person, generated by the local engine. No consent is
 * needed because nobody real is depicted: the prompt is moderated to keep it that way.
 */
export function GenerateForm({ engine, canGenerate, allowance, onCreated }: GenerateFormProps) {
  const { t } = useTranslation('photo-avatar');
  const format = useFormat();
  const session = useSession();

  const [prompt, setPrompt] = useState('');
  const [name, setName] = useState('');
  const [gender, setGender] = useState<Gender>('neutral');
  const [seedText, setSeedText] = useState('');
  const [touched, setTouched] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<ApiError | null>(null);
  const abort = useRef<AbortController | null>(null);
  useEffect(() => () => abort.current?.abort(), []);

  const promptIssue = promptProblem(prompt);
  const nameIssue = nameProblem(name);
  const seed = parseSeed(seedText);
  const cost = CREDIT_COSTS.generatedAvatar;
  const measured = portraitSeconds(engine);
  const blocked = !canGenerate || session.credits < cost || (allowance !== null && !allowance.room);

  const submit = async (event: FormEvent) => {
    event.preventDefault();
    setTouched(true);
    setError(null);
    if (promptIssue || nameIssue || !seed.valid || blocked) return;
    const controller = new AbortController();
    abort.current = controller;
    setBusy(true);
    try {
      const avatar = await apiClient.photoAvatars.generate(
        {
          body: {
            name: name.trim(),
            prompt: prompt.trim(),
            gender,
            ...(seed.seed !== undefined ? { seed: seed.seed } : {}),
          },
        },
        { signal: controller.signal },
      );
      void session.refresh();
      onCreated(avatar);
    } catch (err) {
      const failure = toApiError(err);
      if (failure.code !== 'ABORTED') setError(failure);
    } finally {
      setBusy(false);
    }
  };

  const fieldError = (field: 'name' | 'prompt') =>
    error && isApiError(error) ? error.fieldErrors[field] : undefined;

  return (
    <form onSubmit={(event) => void submit(event)} noValidate className="flex flex-col gap-7">
      <section aria-labelledby="generate-step-1">
        <h2 id="generate-step-1" className="flex items-baseline gap-2.5 text-xl">
          <span className="nums font-mono text-sm text-fg-subtle">01</span>
          {t('generate.describe')}
        </h2>
        <Textarea
          wrapperClassName="mt-3"
          label={t('generate.prompt')}
          hint={t('generate.promptHint')}
          name="prompt"
          rows={4}
          maxLength={PROMPT_MAX}
          showCount
          required
          disabled={busy}
          value={prompt}
          placeholder={t('generate.examples.presenter')}
          error={
            (touched && promptIssue ? t(`problem.${promptIssue}`) : undefined) ??
            fieldError('prompt')
          }
          onChange={(event) => setPrompt(event.target.value)}
        />
        <div className="mt-3 flex flex-wrap items-center gap-2">
          <span className="text-xs font-semibold text-fg-muted">{t('generate.try')}</span>
          {EXAMPLES.map((example) => (
            <button
              key={example}
              type="button"
              disabled={busy}
              onClick={() => setPrompt(t(`generate.examples.${example}`))}
              className="rounded-full border border-line-strong bg-surface px-3 py-1 text-xs font-semibold transition-colors duration-150 hover:bg-surface-2 disabled:opacity-50"
            >
              {t(`generate.exampleNames.${example}`)}
            </button>
          ))}
        </div>
        <Callout
          className="mt-4"
          tone="neutral"
          icon={<UserRoundX />}
          title={t('generate.syntheticTitle')}
        >
          {t('generate.syntheticText')}
        </Callout>
      </section>

      <section aria-labelledby="generate-step-2">
        <h2 id="generate-step-2" className="flex items-baseline gap-2.5 text-xl">
          <span className="nums font-mono text-sm text-fg-subtle">02</span>
          {t('details.title')}
        </h2>
        <div className="mt-3 grid gap-4 sm:grid-cols-[minmax(0,1fr)_auto] sm:items-start">
          <Input
            label={t('details.name')}
            hint={t('details.nameHint')}
            name="name"
            value={name}
            maxLength={NAME_MAX}
            required
            disabled={busy}
            error={
              (touched && nameIssue ? t(`problem.${nameIssue}`) : undefined) ?? fieldError('name')
            }
            onChange={(event) => setName(event.target.value)}
          />
          <div className="flex min-w-0 flex-col gap-1.5">
            <span className="text-sm font-semibold">{t('details.gender')}</span>
            <SegmentedControl
              aria-label={t('details.gender')}
              value={gender}
              onValueChange={setGender}
              disabled={busy}
              options={GENDERS.map((value) => ({ value, label: t(`gender.${value}`) }))}
            />
            <span className="text-sm text-fg-muted">{t('details.genderHint')}</span>
          </div>
        </div>
        <Input
          wrapperClassName="mt-4 max-w-xs"
          label={t('generate.seed')}
          optionalLabel={t('optional')}
          hint={t('generate.seedHint')}
          name="seed"
          inputMode="numeric"
          leading={<Dices aria-hidden="true" />}
          placeholder={t('generate.seedPlaceholder')}
          value={seedText}
          disabled={busy}
          error={touched && !seed.valid ? t('problem.seedInvalid', { max: SEED_MAX }) : undefined}
          onChange={(event) => setSeedText(event.target.value)}
        />
      </section>

      <div className="flex flex-col gap-3 border-t border-line pt-5">
        <CostLine
          cost={cost}
          allowanceFull={allowance !== null && !allowance.room}
          allowanceText={
            allowance
              ? t('allowance', {
                  used: allowance.used,
                  max: allowance.max,
                  plan: session.plan.name,
                })
              : null
          }
        />
        {canGenerate ? (
          <p className="flex items-start gap-2 text-sm text-fg-muted">
            <Timer aria-hidden="true" className="mt-0.5 size-4 shrink-0" />
            {measured !== null
              ? t('generate.time.measured', { time: format.duration(measured * 1000) })
              : t('generate.time.unmeasured')}
          </p>
        ) : (
          <Callout tone="warning" role="status" title={t('generate.engineOffTitle')}>
            {t('generate.engineOffText')}
          </Callout>
        )}
        {error && <FailureNote error={error} />}
        <div className="flex flex-wrap items-center gap-3">
          <Button
            type="submit"
            variant="primary"
            size="lg"
            leftIcon={<Sparkles aria-hidden="true" />}
            loading={busy}
            disabled={blocked}
          >
            {t('generate.submit')}
          </Button>
          <p className="min-w-0 flex-1 basis-56 text-xs text-pretty text-fg-muted">
            {t('generate.submitHint')}
          </p>
        </div>
      </div>
    </form>
  );
}
