import { AgeGroupSchema, AvatarStyleSchema, GenderSchema } from '@parlante/shared';
import type { AgeGroup, Avatar, AvatarStyle, Gender } from '@parlante/shared';

/* Filters of the avatar library. The catalogue is small (stock + what the workspace created),
 * so it is fetched once and narrowed here: counts per shelf stay visible while filtering and
 * typing in the search box never waits for the network. State lives in the URL. */

/** The shelves of the library. */
export const AVATAR_VIEWS = ['all', 'instant', 'photoreal', 'mine'] as const;
export type AvatarView = (typeof AVATAR_VIEWS)[number];

/** How an avatar is presented: where it comes from and how it is animated. */
export type AvatarOrigin =
  /** Built-in 2D parametric character, drawn in real time. */
  | 'instant'
  /** Built-in photorealistic synthetic person. */
  | 'stockPhotoreal'
  /** Created by the workspace from a photo of a real person. */
  | 'photo'
  /** Synthetic person generated by the workspace from a description. */
  | 'generated';

export function avatarOrigin(avatar: Pick<Avatar, 'kind' | 'rendering'>): AvatarOrigin {
  if (avatar.kind === 'photo') return 'photo';
  if (avatar.kind === 'generated') return 'generated';
  return avatar.rendering === 'instant' ? 'instant' : 'stockPhotoreal';
}

export function isOwnAvatar(avatar: Pick<Avatar, 'kind'>): boolean {
  return avatar.kind !== 'stock';
}

export interface AvatarFilters {
  view: AvatarView;
  gender: Gender | null;
  ageGroup: AgeGroup | null;
  style: AvatarStyle | null;
  q: string;
}

export const NO_FILTERS: AvatarFilters = {
  view: 'all',
  gender: null,
  ageGroup: null,
  style: null,
  q: '',
};

export function hasActiveFilters(filters: AvatarFilters): boolean {
  return (
    filters.gender !== null ||
    filters.ageGroup !== null ||
    filters.style !== null ||
    filters.q.trim() !== ''
  );
}

/** Lower-case, accent-free: "Lucía" matches "lucia". */
export function normalizeText(text: string): string {
  return text
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .toLowerCase()
    .trim();
}

function matchesView(avatar: Avatar, view: AvatarView): boolean {
  switch (view) {
    case 'all':
      return true;
    case 'instant':
      return avatar.rendering === 'instant';
    case 'photoreal':
      return avatar.rendering === 'photoreal';
    case 'mine':
      return isOwnAvatar(avatar);
  }
}

/** Every word typed must appear in the name, description, tags or prompt. */
export function matchesSearch(avatar: Avatar, q: string): boolean {
  const words = normalizeText(q).split(/\s+/).filter(Boolean);
  if (words.length === 0) return true;
  const haystack = normalizeText(
    [avatar.name, avatar.description, ...avatar.tags, avatar.prompt ?? ''].join(' '),
  );
  return words.every((word) => haystack.includes(word));
}

/** Traits other than the shelf (`view`). */
function matchesTraits(avatar: Avatar, filters: AvatarFilters): boolean {
  if (filters.gender !== null && avatar.gender !== filters.gender) return false;
  if (filters.ageGroup !== null && avatar.ageGroup !== filters.ageGroup) return false;
  if (filters.style !== null && avatar.style !== filters.style) return false;
  return matchesSearch(avatar, filters.q);
}

export function filterAvatars(avatars: readonly Avatar[], filters: AvatarFilters): Avatar[] {
  return avatars.filter(
    (avatar) => matchesView(avatar, filters.view) && matchesTraits(avatar, filters),
  );
}

/** How many avatars each shelf holds with the current trait filters and search. */
export function countByView(
  avatars: readonly Avatar[],
  filters: AvatarFilters,
): Record<AvatarView, number> {
  const counts: Record<AvatarView, number> = { all: 0, instant: 0, photoreal: 0, mine: 0 };
  for (const avatar of avatars) {
    if (!matchesTraits(avatar, filters)) continue;
    for (const view of AVATAR_VIEWS) if (matchesView(avatar, view)) counts[view] += 1;
  }
  return counts;
}

export interface AvatarShelf {
  origin: 'instant' | 'stockPhotoreal' | 'mine';
  avatars: Avatar[];
}

/**
 * The filtered avatars grouped the way the page shows them: the workspace's own avatars
 * first (what the person made), then instant 2D, then the photorealistic stock. Empty
 * shelves are dropped.
 */
export function shelvesOf(avatars: readonly Avatar[]): AvatarShelf[] {
  const mine: Avatar[] = [];
  const instant: Avatar[] = [];
  const stockPhotoreal: Avatar[] = [];
  for (const avatar of avatars) {
    if (isOwnAvatar(avatar)) mine.push(avatar);
    else if (avatar.rendering === 'instant') instant.push(avatar);
    else stockPhotoreal.push(avatar);
  }
  const shelves: AvatarShelf[] = [
    { origin: 'mine', avatars: mine },
    { origin: 'instant', avatars: instant },
    { origin: 'stockPhotoreal', avatars: stockPhotoreal },
  ];
  return shelves.filter((shelf) => shelf.avatars.length > 0);
}

/* ---------- URL ---------- */

function pick<T extends string>(value: string | null, allowed: readonly T[]): T | null {
  return value !== null && (allowed as readonly string[]).includes(value) ? (value as T) : null;
}

export function filtersFromParams(params: URLSearchParams): AvatarFilters {
  return {
    view: pick(params.get('view'), AVATAR_VIEWS) ?? 'all',
    gender: pick(params.get('gender'), GenderSchema.options),
    ageGroup: pick(params.get('age'), AgeGroupSchema.options),
    style: pick(params.get('style'), AvatarStyleSchema.options),
    q: params.get('q') ?? '',
  };
}

/** Write the filters into `params` (other keys, such as the open avatar, are kept). */
export function filtersToParams(filters: AvatarFilters, params: URLSearchParams): URLSearchParams {
  const next = new URLSearchParams(params);
  const set = (key: string, value: string | null, fallback: string) => {
    if (value === null || value === fallback) next.delete(key);
    else next.set(key, value);
  };
  set('view', filters.view, 'all');
  set('gender', filters.gender, '');
  set('age', filters.ageGroup, '');
  set('style', filters.style, '');
  set('q', filters.q.trim() === '' ? null : filters.q, '');
  return next;
}
